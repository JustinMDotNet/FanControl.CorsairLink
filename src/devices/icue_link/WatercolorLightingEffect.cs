        0xff,0xdf,0xf8, 0xff,0xea,0xfa, 0xff,0xf5,0xfd, 0xff,0xfc,0xfa, 0xff,0xff,0xf3, 0xff,0xff,0xe8, 0xff,0xff,0xd4, 0xff,0xff,0xc2,
